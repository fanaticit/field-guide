const ROMAN_RANK_ORDER = ['I', 'II', 'III', 'IV', 'V', 'VI'];
const ROMAN_REGEX = /\b(I|II|III|IV|V|VI)\b\s*$/;

/**
 * Extracts Roman numeral ranks (I, II, III, IV, V, VI) from monster material item names.
 * Skips generic progression materials like Hunter's Jade.
 */
export function getMonsterRanksFromMaterials(materials: GearMaterialRequirement[]): string[] {
  const ranks = new Set<string>();
  for (const m of materials) {
    if (/Jade/i.test(m.item)) continue;
    const match = m.item.match(ROMAN_REGEX);
    if (match) {
      ranks.add(match[1]);
    }
  }
  return Array.from(ranks).sort(
    (a, b) => ROMAN_RANK_ORDER.indexOf(a) - ROMAN_RANK_ORDER.indexOf(b),
  );
}

/**
 * Returns the materials required for the current step (crafting or upgrading) of a challenge.
 */
export function getChallengeRequiredMaterials(
  challenge: {
    status: string;
    current_rarity?: number | null;
    armour_piece_id?: string | null;
    weapon_id?: string | null;
  },
  armourUpgradesMap?: Map<string, Map<number, GearMaterialRequirement[]>>,
): GearMaterialRequirement[] {
  if (challenge.status === 'completed' || challenge.status === 'abandoned') {
    return [];
  }
  if (challenge.armour_piece_id) {
    if (challenge.status === 'crafting' || (challenge.current_rarity ?? 0) === 0) {
      return ARMOUR_FORGE_MATERIALS[challenge.armour_piece_id] ?? [];
    }
    const targetRarity = (challenge.current_rarity ?? 0) + 1;
    const upgradeMats = armourUpgradesMap?.get(challenge.armour_piece_id)?.get(targetRarity);
    if (upgradeMats && upgradeMats.length > 0) {
      return upgradeMats;
    }
    if (targetRarity === 1) {
      return ARMOUR_FORGE_MATERIALS[challenge.armour_piece_id] ?? [];
    }
  }
  if (challenge.weapon_id) {
    if (challenge.status === 'crafting' || (challenge.current_rarity ?? 0) === 0) {
      return WEAPON_FORGE_MATERIALS[challenge.weapon_id] ?? [];
    }
  }
  return [];
}

