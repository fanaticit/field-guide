/** Sorted for UI display (by tier priority then name) */
export const MONSTERS_SORTED = [...MONSTERS].sort((a, b) => {
  const tierOrder: Record<string, number> = { low: 0, high: 1, elder: 2, small: 3, event: 4 };
  const ta = tierOrder[a.tier] ?? 99;
  const tb = tierOrder[b.tier] ?? 99;
  if (ta !== tb) return ta - tb;
  return a.name.localeCompare(b.name);
});

export const MONSTER_MAP = new Map<string, CoreMonster>(MONSTERS.map((m) => [m.id, m]));

/** Get all variants of a given base monster */
export function getVariants(baseId: string): CoreMonster[] {
  return MONSTERS.filter((m) => m.parentId === baseId);
}

/** Get just base monsters (not variants) */
export const BASE_MONSTERS = MONSTERS.filter((m) => !m.isVariant);

/** Get monsters by species */
export function getMonstersBySpecies(species: string): CoreMonster[] {
  return MONSTERS.filter((m) => m.species === species);
}

/** Get monsters by tier */
export function getMonstersByTier(tier: string): CoreMonster[] {
  return MONSTERS.filter((m) => m.tier === tier);
}

/** Get monsters weak to a specific element */
export function getMonstersWeakTo(element: string): CoreMonster[] {
  return MONSTERS.filter((m) => m.weaknesses.includes(element as never));
}
