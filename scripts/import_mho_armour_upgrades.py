#!/usr/bin/env python3
"""
Generate the armour upgrade import migration from import/MHO_armour_upgrades.json.

Creates public.armour_piece_upgrades: one row per armour piece per rarity step
(starting rarity .. max rarity), linked to armour_pieces by armour_piece_id.

  rarity             = the rarity level this row describes
  defence            = total defence at this rarity
  defence_gain       = defence gained by upgrading to this rarity (NULL at the start)
  required_level     = adventurer level needed to upgrade to this rarity
  materials          = [{"item_id": 71001, "item": "Hunter's Jade I", "count": 1}]
  skills             = skill ids the piece has at this rarity (skills table ids)
  skill_changes      = [{"type": "new_skill" | "level_up", "skill_id": "..."}]

It also sets armour_pieces.max_rarity and refreshes armour_pieces.skills with the
skills of the highest rarity (the game's own ids, which resolves skills whose name
exists more than once). armour_pieces.rarity stays the starting rarity.

Usage (after updating the JSON when the game changes):
  python3 scripts/import_mho_armour_upgrades.py [--out supabase/migrations/<ts>_import_mho_armour_upgrades.sql]
"""
import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "import" / "MHO_armour_upgrades.json"
DEFAULT_OUT = ROOT / "supabase" / "migrations" / "20261104000012_import_mho_armour_upgrades.sql"

CHANGE_TYPES = {"New skill": "new_skill", "Level up": "level_up"}


def sql_str(value):
    return "'" + str(value).replace("'", "''") + "'"


def sql_json(value):
    return sql_str(json.dumps(value, separators=(",", ":"), ensure_ascii=False)) + "::JSONB"


def sql_int(value):
    return "NULL" if value is None else str(int(value))


def build_rows():
    armours = json.loads(JSON_PATH.read_text(encoding="utf-8"))
    rows, maxes = [], {}
    for a in armours:
        piece_id = str(a["id"])
        # skill changes are listed per unlock rarity in skill_unlocks
        changes_by_rarity = {}
        for unlock in a["skill_unlocks"]:
            changes = []
            for c in unlock["changes"]:
                kind = next((v for k, v in CHANGE_TYPES.items() if c["change"].startswith(k)), None)
                if kind is None:
                    sys.exit(f"Unknown skill change '{c['change']}' on {piece_id}")
                changes.append({"type": kind, "skill_id": str(c["id"])})
            changes_by_rarity[unlock["rarity"]] = changes

        path = a["upgrade_path"]
        if path[0]["rarity"] != a["starting_rarity"] or path[-1]["rarity"] != a["max_rarity"]:
            sys.exit(f"Upgrade path of {piece_id} does not match starting/max rarity")
        maxes[piece_id] = a["max_rarity"]

        for step in path:
            materials = [
                {"item_id": m["item_id"], "item": m["item"], "count": m["count"]}
                for m in step.get("materials", [])
            ]
            rows.append(
                {
                    "piece": piece_id,
                    "rarity": step["rarity"],
                    "defence": step["defence"],
                    "defence_gain": step.get("defence_gain"),
                    "required_level": step.get("required_level"),
                    "growth_points": step.get("growth_points"),
                    "money": step.get("money"),
                    "progression_level": step.get("progression_level"),
                    "materials": materials,
                    "other_gains": step.get("other_gains") or {},
                    "skills": [str(s["id"]) for s in step["skills"]],
                    "skill_changes": changes_by_rarity.get(step["rarity"], []),
                }
            )
    return rows, maxes


def render(rows):
    def row(r):
        skills = "ARRAY[" + ", ".join(sql_str(s) for s in r["skills"]) + "]::TEXT[]"
        return "  ({piece}, {rarity}, {defence}, {gain}, {level}, {gp}, {money}, {prog}, {materials}, {other}, {skills}, {changes})".format(
            piece=sql_str(r["piece"]),
            rarity=r["rarity"],
            defence=sql_int(r["defence"]),
            gain=sql_int(r["defence_gain"]),
            level=sql_int(r["required_level"]),
            gp=sql_int(r["growth_points"]),
            money=sql_int(r["money"]),
            prog=sql_int(r["progression_level"]),
            materials=sql_json(r["materials"]),
            other=sql_json(r["other_gains"]),
            skills=skills,
            changes=sql_json(r["skill_changes"]),
        )

    values = ",\n".join(row(r) for r in rows)
    return f"""-- ============================================================
-- Migration: 20261104000012 — Armour upgrades (rarity steps per armour piece)
-- Source: import/MHO_armour_upgrades.json — generated by scripts/import_mho_armour_upgrades.py
-- DO NOT edit by hand — update the JSON and re-run the script.
--   * armour_piece_upgrades: one row per armour piece per rarity step, linked to armour_pieces
--   * armour_pieces.rarity = starting rarity, armour_pieces.max_rarity = highest rarity
--   * armour_pieces.skills is refreshed with the skills at the highest rarity
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.armour_piece_upgrades (
  armour_piece_id   TEXT        NOT NULL REFERENCES public.armour_pieces(id) ON DELETE CASCADE,
  rarity            INTEGER     NOT NULL,
  defence           INTEGER,
  defence_gain      INTEGER,
  required_level    INTEGER,
  growth_points     INTEGER,
  money             INTEGER,
  progression_level INTEGER,
  -- [{{"item_id": 71001, "item": "Hunter's Jade I", "count": 1}}]
  materials         JSONB       NOT NULL DEFAULT '[]',
  other_gains       JSONB       NOT NULL DEFAULT '{{}}',
  -- skills table ids the piece has at this rarity
  skills            TEXT[]      NOT NULL DEFAULT '{{}}',
  -- [{{"type": "new_skill" | "level_up", "skill_id": "<skills.id>"}}] gained at this rarity
  skill_changes     JSONB       NOT NULL DEFAULT '[]',
  PRIMARY KEY (armour_piece_id, rarity)
);

CREATE INDEX IF NOT EXISTS idx_armour_piece_upgrades_skills ON public.armour_piece_upgrades USING GIN(skills);

ALTER TABLE public.armour_piece_upgrades ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "armour_piece_upgrades_select_all" ON public.armour_piece_upgrades;
CREATE POLICY "armour_piece_upgrades_select_all"
  ON public.armour_piece_upgrades FOR SELECT USING (true);

DROP POLICY IF EXISTS "armour_piece_upgrades_write_admin" ON public.armour_piece_upgrades;
CREATE POLICY "armour_piece_upgrades_write_admin"
  ON public.armour_piece_upgrades FOR ALL
  USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));

ALTER TABLE public.armour_pieces ADD COLUMN IF NOT EXISTS max_rarity INTEGER;

DELETE FROM public.armour_piece_upgrades;

INSERT INTO public.armour_piece_upgrades
  (armour_piece_id, rarity, defence, defence_gain, required_level, growth_points, money, progression_level, materials, other_gains, skills, skill_changes)
VALUES
{values};

UPDATE public.armour_pieces p
SET max_rarity = m.max_rarity
FROM (
  SELECT armour_piece_id, MAX(rarity) AS max_rarity FROM public.armour_piece_upgrades GROUP BY armour_piece_id
) m
WHERE p.id = m.armour_piece_id;

UPDATE public.armour_pieces p
SET skills = u.skills
FROM public.armour_piece_upgrades u
WHERE u.armour_piece_id = p.id AND u.rarity = p.max_rarity;

COMMIT;
"""


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", default=str(DEFAULT_OUT))
    args = parser.parse_args()
    rows, maxes = build_rows()
    Path(args.out).write_text(render(rows), encoding="utf-8")
    print(f"{len(rows)} upgrade rows for {len(maxes)} armour pieces -> {args.out}")


if __name__ == "__main__":
    main()
