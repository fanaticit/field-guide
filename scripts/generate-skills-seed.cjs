#!/usr/bin/env node
// scripts/generate-skills-seed.cjs
// Reads hc_data/skills-metadata.json and outputs supabase/seeds/skills.sql
// Run: node scripts/generate-skills-seed.cjs

const fs = require('fs');
const path = require('path');

const raw = JSON.parse(fs.readFileSync(path.join(__dirname, '../hc_data/skills-metadata.json'), 'utf8'));
const skillsMetadata = raw.skillsMetadata;

/** Convert a snake_case skill ID to Title Case display name */
function toDisplayName(id) {
  return id
    .split('_')
    .map((w) => w.charAt(0).toUpperCase() + w.slice(1))
    .join(' ');
}

// Explicit category fallbacks for skills missing type in hc_data
const TYPE_OVERRIDES = {
  earplugs: 'general',
  buildup_boost: 'status',
  special_partbreaker: 'general',
  shared_sword: 'general',
  velkhana_aegis: 'general',
  normal_element_ammo_boost: 'general',
};

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

const lines = [
  '-- Auto-generated by scripts/generate-skills-seed.cjs',
  '-- DO NOT edit by hand — re-run the script',
  '',
  'BEGIN;',
  '',
];

const entries = Object.entries(skillsMetadata);

for (const [id, meta] of entries) {
  const name = toDisplayName(id);
  const category = meta.type || TYPE_OVERRIDES[id] || 'general';
  const maxLevel = meta.maxLevel || 5;
  const maxLevelsJson = JSON.stringify({ mhn: maxLevel });

  lines.push(`INSERT INTO public.skills`);
  lines.push(`  (id, name, name_ja, category, games, max_levels, is_active, icon, sort_orders, notes, description)`);
  lines.push(`VALUES (`);
  lines.push(`  ${escapeSql(id)},`);
  lines.push(`  ${escapeSql(name)},`);
  lines.push(`  NULL,`);
  lines.push(`  ${escapeSql(category)},`);
  lines.push(`  ARRAY['mhn']::TEXT[],`);
  lines.push(`  ${escapeSql(maxLevelsJson)}::JSONB,`);
  lines.push(`  TRUE,`);
  lines.push(`  NULL,`);
  lines.push(`  '{}'::JSONB,`);
  lines.push(`  NULL,`);
  lines.push(`  NULL`);
  lines.push(`) ON CONFLICT (id) DO UPDATE SET`);
  lines.push(`  name = EXCLUDED.name,`);
  lines.push(`  category = EXCLUDED.category,`);
  lines.push(`  max_levels = COALESCE(public.skills.max_levels, EXCLUDED.max_levels),`);
  lines.push(`  games = COALESCE(public.skills.games, EXCLUDED.games);`);
  lines.push('');
}

lines.push('COMMIT;');
lines.push('');

const outPath = path.join(__dirname, '../supabase/seeds/skills.sql');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Generated ${entries.length} skills in ${outPath}`);
