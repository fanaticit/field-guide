#!/usr/bin/env python3
"""
Generate the adventurer bond-gift migration from import/MHO_adventurer_gifts.csv and copy the
gift icons from "import/image add/ItemIcon" into public/images/gifts/.

  adventurer_gift_items        one row per gift (id = Gift ID): name, category, description, icon, base_bond
  adventurer_gift_preferences  one row per adventurer per gift: preference, multiplier (%), bond_gained

Rows with Debug = yes are skipped, and preferences are only inserted for adventurers that exist in
public.adventurers. The migration upserts, so it is safe to re-run after the CSV changes.

Usage:
  python3 scripts/import_mho_adventurer_gifts.py [--out supabase/migrations/<ts>_import_mho_adventurer_gifts.sql]
"""
import argparse
import csv
import datetime as dt
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "import" / "MHO_adventurer_gifts.csv"
ICON_SRC = ROOT / "import" / "image add" / "ItemIcon"
ICON_DST = ROOT / "public" / "images" / "gifts"
ICON_URL = "/images/gifts/"
MIGRATIONS = ROOT / "supabase" / "migrations"
PREFS = {"Favourite": "favourite", "Neutral": "neutral", "Disliked": "disliked"}


def q(v):
    if v is None or v == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def next_stamp():
    today = dt.datetime.now().strftime("%Y%m%d")
    seqs = [int(p.name[8:14]) for p in MIGRATIONS.glob(f"{today}*_*.sql") if p.name[8:14].isdigit()]
    return f"{today}{(max(seqs) + 1 if seqs else 1):06d}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    args = ap.parse_args()

    rows = [r for r in csv.DictReader(open(CSV_PATH, encoding="utf-8-sig", newline=""))
            if (r.get("Debug") or "").strip().lower() != "yes"]

    items, prefs, icons, problems = {}, [], set(), []
    for r in rows:
        gid = r["Gift ID"].strip()
        icon_file = r["Gift icon"].strip().split("/")[-1]
        if icon_file and not (ICON_SRC / icon_file).exists() and not (ICON_DST / icon_file).exists():
            problems.append(f"Missing icon {icon_file} for gift {gid}")
        icons.add(icon_file)
        item = {
            "id": gid, "name": r["Gift"].strip(), "category": r["Gift category"].strip(),
            "description": r["Gift description"].strip(), "icon": ICON_URL + icon_file if icon_file else None,
            "base_bond": int(r["Base Bond"]),
        }
        if gid in items and items[gid] != item:
            problems.append(f"Gift {gid} has different details on different rows")
        items[gid] = item
        pref = r["Preference"].strip()
        if pref not in PREFS:
            problems.append(f"Unknown preference '{pref}' ({r['Adventurer']} / {r['Gift']})")
            continue
        prefs.append((r["Adventurer ID"].strip(), gid, PREFS[pref],
                      int(r["Bond multiplier"].strip().rstrip("%")), int(r["Bond gained"])))
    if problems:
        sys.exit("\n".join(problems))

    stamp = next_stamp()
    out = Path(args.out) if args.out else MIGRATIONS / f"{stamp}_import_mho_adventurer_gifts.sql"
    item_rows = ",\n".join(
        f"  ({q(i['id'])}, {q(i['name'])}, {q(i['category'])}, {q(i['description'])}, {q(i['icon'])}, {i['base_bond']}, {n})"
        for n, i in enumerate(sorted(items.values(), key=lambda x: int(x["id"])), start=1))
    pref_rows = ",\n".join(f"  ({q(a)}, {q(g)}, {q(p)}, {m}, {b})" for a, g, p, m, b in prefs)

    sql = f"""-- ============================================================
-- Migration: {out.stem.split('_')[0]} — Adventurer bond gifts
-- Source: import/MHO_adventurer_gifts.csv — generated by scripts/import_mho_adventurer_gifts.py
--   * adventurer_gift_items: the gifts (icon in /images/gifts/)
--   * adventurer_gift_preferences: each adventurer's preference, multiplier and bond gained per gift
--   * debug rows skipped; preferences only for adventurers in public.adventurers; safe to re-run
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.adventurer_gift_items (
  id          TEXT    PRIMARY KEY,
  name        TEXT    NOT NULL,
  category    TEXT,
  description TEXT,
  icon        TEXT,
  base_bond   INTEGER NOT NULL DEFAULT 0,
  sort_order  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.adventurer_gift_preferences (
  adventurer_id TEXT    NOT NULL REFERENCES public.adventurers(id) ON UPDATE CASCADE ON DELETE CASCADE,
  gift_id       TEXT    NOT NULL REFERENCES public.adventurer_gift_items(id) ON UPDATE CASCADE ON DELETE CASCADE,
  preference    TEXT    NOT NULL CHECK (preference IN ('favourite', 'neutral', 'disliked')),
  multiplier    INTEGER NOT NULL DEFAULT 100,  -- percent, e.g. 150
  bond_gained   INTEGER NOT NULL DEFAULT 0,
  PRIMARY KEY (adventurer_id, gift_id)
);
CREATE INDEX IF NOT EXISTS idx_adventurer_gift_preferences_adventurer
  ON public.adventurer_gift_preferences(adventurer_id);

ALTER TABLE public.adventurer_gift_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.adventurer_gift_preferences ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "adventurer_gift_items_select_all" ON public.adventurer_gift_items;
CREATE POLICY "adventurer_gift_items_select_all" ON public.adventurer_gift_items FOR SELECT USING (TRUE);
DROP POLICY IF EXISTS "adventurer_gift_items_admin_all" ON public.adventurer_gift_items;
CREATE POLICY "adventurer_gift_items_admin_all" ON public.adventurer_gift_items FOR ALL
  USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));

DROP POLICY IF EXISTS "adventurer_gift_preferences_select_all" ON public.adventurer_gift_preferences;
CREATE POLICY "adventurer_gift_preferences_select_all" ON public.adventurer_gift_preferences FOR SELECT USING (TRUE);
DROP POLICY IF EXISTS "adventurer_gift_preferences_admin_all" ON public.adventurer_gift_preferences;
CREATE POLICY "adventurer_gift_preferences_admin_all" ON public.adventurer_gift_preferences FOR ALL
  USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));

INSERT INTO public.adventurer_gift_items (id, name, category, description, icon, base_bond, sort_order) VALUES
{item_rows}
ON CONFLICT (id) DO UPDATE SET
  name = EXCLUDED.name, category = EXCLUDED.category, description = EXCLUDED.description,
  icon = EXCLUDED.icon, base_bond = EXCLUDED.base_bond, sort_order = EXCLUDED.sort_order;

CREATE TEMP TABLE _gift_prefs (
  adventurer_id TEXT, gift_id TEXT, preference TEXT, multiplier INTEGER, bond_gained INTEGER
) ON COMMIT DROP;

INSERT INTO _gift_prefs VALUES
{pref_rows};

INSERT INTO public.adventurer_gift_preferences (adventurer_id, gift_id, preference, multiplier, bond_gained)
SELECT p.adventurer_id, p.gift_id, p.preference, p.multiplier, p.bond_gained
FROM _gift_prefs p
WHERE EXISTS (SELECT 1 FROM public.adventurers a WHERE a.id = p.adventurer_id)
ON CONFLICT (adventurer_id, gift_id) DO UPDATE SET
  preference = EXCLUDED.preference, multiplier = EXCLUDED.multiplier, bond_gained = EXCLUDED.bond_gained;

COMMIT;
"""
    out.write_text(sql, encoding="utf-8")

    ICON_DST.mkdir(parents=True, exist_ok=True)
    copied = 0
    for f in sorted(icons):
        if f and (ICON_SRC / f).exists() and not (ICON_DST / f).exists():
            shutil.copy2(ICON_SRC / f, ICON_DST / f)
            copied += 1
    adv = len({p[0] for p in prefs})
    print(f"{len(items)} gifts, {len(prefs)} preferences for {adv} adventurers, {copied} icons copied -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
