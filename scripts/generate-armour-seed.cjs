#!/usr/bin/env node
// scripts/generate-armour-seed.cjs
// Reads hc_data/armor-equipment-skills.json and outputs supabase/seeds/armour_pieces.sql
// Run: node scripts/generate-armour-seed.cjs

const fs = require('fs');
const path = require('path');

const raw = JSON.parse(fs.readFileSync(path.join(__dirname, '../hc_data/armor-equipment-skills.json'), 'utf8'));
const armorEquipmentSkills = raw.armorEquipmentSkills;

const ARMOUR_SLOTS = ['helm', 'chest', 'gloves', 'waist', 'greaves'];

function escapeSql(str) {
  if (str === null || str === undefined) return 'NULL';
  return `'${String(str).replace(/'/g, "''")}'`;
}

const lines = [
  '-- Auto-generated by scripts/generate-armour-seed.cjs',
  '-- DO NOT edit by hand — re-run the script',
  '',
  'BEGIN;',
  '',
];

let pieceCount = 0;

for (const [monsterId, slotsData] of Object.entries(armorEquipmentSkills)) {
  for (const slot of ARMOUR_SLOTS) {
    const rawSkills = slotsData[slot] || [];
    const skills = rawSkills.map((s) => ({
      id: s.id,
      level: Number(s.level) || 1,
    }));
    const id = `mhn:${monsterId}:${slot}`;
    const skillsJson = JSON.stringify(skills);

    lines.push(`INSERT INTO public.armour_pieces`);
    lines.push(`  (id, game, monster_id, slot, skills, driftsmelt_slots, is_active, notes)`);
    lines.push(`VALUES (`);
    lines.push(`  ${escapeSql(id)},`);
    lines.push(`  'mhn',`);
    lines.push(`  ${escapeSql(monsterId)},`);
    lines.push(`  ${escapeSql(slot)},`);
    lines.push(`  ${escapeSql(skillsJson)}::JSONB,`);
    lines.push(`  0,`);
    lines.push(`  TRUE,`);
    lines.push(`  NULL`);
    lines.push(`) ON CONFLICT (game, monster_id, slot) DO UPDATE SET`);
    lines.push(`  skills = EXCLUDED.skills;`);
    lines.push('');
    pieceCount++;
  }
}

lines.push('COMMIT;');
lines.push('');

const outPath = path.join(__dirname, '../supabase/seeds/armour_pieces.sql');
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Generated ${pieceCount} armour pieces for ${Object.keys(armorEquipmentSkills).length} monsters in ${outPath}`);
