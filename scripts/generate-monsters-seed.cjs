function sqlStr(val) {
  if (val === null || val === undefined) return 'NULL';
  return `'${String(val).replace(/'/g, "''")}'`;
}

function sqlArr(arr) {
  if (!arr || arr.length === 0) return "'{}'";
  return `ARRAY[${arr.map(v => sqlStr(v)).join(', ')}]::TEXT[]`;
}

function sqlJsonb(obj) {
  return `'${JSON.stringify(obj)}'::jsonb`;
}

const lines = [
  '-- Auto-generated by scripts/generate-monsters-seed.cjs',
  '-- DO NOT edit by hand — re-run the script',
  '-- sort_orders stores per-game positions: { "mhn": 10, "mho": 5 }',
  '',
];
lines.push('BEGIN;');
lines.push('');

for (const m of monsters) {
  const elements = Array.isArray(m.element)
    ? m.element
    : m.element ? [m.element] : [];

  const weaknesses = Array.isArray(m.weaknesses) ? m.weaknesses : [];
  const isSmall = m.type === 'small' || m.type === 'collab';
  const tier = isSmall ? (m.type || 'small') : (m.tier || 'low');
  const species = SPECIES_MAP[m.id] || null;
  const parentId = PARENT_MAP[m.id] || null;
  const isVariant = !!parentId;
  const games = "ARRAY['mhn']::TEXT[]";

  // Build per-game sort_orders JSONB — MHN only at seed time
  const sortOrders = m.sortOrder !== undefined
    ? { mhn: m.sortOrder }
    : {};

  lines.push(`INSERT INTO public.monsters`);
  lines.push(`  (id, name, name_ja, species, tier, elements, weaknesses, is_variant, parent_id, games, is_active, icon, sort_orders)`);
  lines.push(`VALUES (`);
  lines.push(`  ${sqlStr(m.id)},`);
  lines.push(`  ${sqlStr(m.name)},`);
  lines.push(`  ${sqlStr(m.nameJa)},`);
  lines.push(`  ${sqlStr(species)},`);
  lines.push(`  ${sqlStr(tier)},`);
  lines.push(`  ${sqlArr(elements)},`);
  lines.push(`  ${sqlArr(weaknesses)},`);
  lines.push(`  ${isVariant},`);
  lines.push(`  ${sqlStr(parentId)},`);
  lines.push(`  ${games},`);
  lines.push(`  TRUE,`);
  lines.push(`  ${sqlStr(m.icon)},`);
  lines.push(`  ${sqlJsonb(sortOrders)}`);
  lines.push(`) ON CONFLICT (id) DO UPDATE SET`);
  lines.push(`  name = EXCLUDED.name,`);
  lines.push(`  name_ja = EXCLUDED.name_ja,`);
  lines.push(`  species = COALESCE(public.monsters.species, EXCLUDED.species),`);
  lines.push(`  tier = EXCLUDED.tier,`);
  lines.push(`  elements = EXCLUDED.elements,`);
  lines.push(`  weaknesses = EXCLUDED.weaknesses,`);
  lines.push(`  is_variant = EXCLUDED.is_variant,`);
  lines.push(`  parent_id = EXCLUDED.parent_id,`);
  lines.push(`  icon = EXCLUDED.icon,`);
  // Merge sort_orders: preserve any MHO entries the admin has set, only update mhn key
  lines.push(`  sort_orders = public.monsters.sort_orders || EXCLUDED.sort_orders;`);
  lines.push('');
}

lines.push('COMMIT;');

const outDir = path.join(__dirname, '../supabase/seeds');
if (!fs.existsSync(outDir)) fs.mkdirSync(outDir, { recursive: true });

const outFile = path.join(outDir, 'monsters.sql');
fs.writeFileSync(outFile, lines.join('\n'));
console.log(`✓ Generated ${monsters.length} monster INSERT statements → ${outFile}`);
