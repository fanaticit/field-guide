#!/usr/bin/env python3
"""
Generate the Investigation Journey migration from import/MHO_monster_investigation_journey.json.

  investigation_journey_steps  one row per journey step (row_id from the export, e.g. 101):
                               the monster it unlocks, the server age / total studies / monster
                               studies it needs, what unlocking does and the rewards

Monsters are linked to public.monsters by the field-guide id (from import/MHO_monsters.csv, matched
by name) with a fallback on the monster name, so the links survive id changes. Steps that are no
longer in the export are deleted, so the migration is safe to re-run after a new export.

Usage:
  python3 scripts/import_mho_investigation_journey.py [--out supabase/migrations/<ts>_import_mho_investigation_journey.sql]
"""
import argparse
import csv
import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
JSON_PATH = ROOT / "import" / "MHO_monster_investigation_journey.json"
MONSTERS_CSV = ROOT / "import" / "MHO_monsters.csv"
MIGRATIONS = ROOT / "supabase" / "migrations"


def q(v):
    if v is None or v == "":
        return "NULL"
    return "'" + str(v).replace("'", "''") + "'"


def n(v):
    return "NULL" if v in (None, "") else str(int(v))


def js(v):
    return q(json.dumps(v, ensure_ascii=False)) + "::jsonb"


def next_stamp():
    today = dt.datetime.now().strftime("%Y%m%d")
    seqs = [int(p.name[8:14]) for p in MIGRATIONS.glob(f"{today}*_*.sql") if p.name[8:14].isdigit()]
    return f"{today}{(max(seqs) + 1 if seqs else 1):06d}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out")
    args = ap.parse_args()

    data = json.load(open(JSON_PATH, encoding="utf-8"))
    monster_ids = {r["Name"].strip(): r["ID"].strip()
                   for r in csv.DictReader(open(MONSTERS_CSV, encoding="utf-8-sig", newline=""))}

    rows, problems, seen = [], [], set()
    for s in data["steps"]:
        rid = str(s["row_id"])
        if rid in seen:
            problems.append(f"Duplicate row_id {rid}")
        seen.add(rid)
        unlocks = (s.get("unlocks") or "").strip()
        grand = bool(s.get("is_grand_prize"))
        studies_of = (s.get("monster_studies_of") or "").strip()
        note_ids = [r.get("monster_note_id") for r in s.get("requirements", []) if r.get("kind") == "Monster studies"]
        unlock_id = None if grand else monster_ids.get(unlocks)
        studies_id = str(note_ids[0]) if note_ids and note_ids[0] else monster_ids.get(studies_of) if studies_of else None
        if not grand and not unlock_id:
            problems.append(f"Step {rid}: no field-guide monster named '{unlocks}' in MHO_monsters.csv")
        if studies_of and not studies_id:
            problems.append(f"Step {rid}: no field-guide monster named '{studies_of}'")
        rows.append({
            "id": rid, "journey": s["journey"], "step": s["step"], "sort_order": s.get("order") or 0,
            "unlocks_name": unlocks, "unlocks_monster_id": unlock_id, "is_grand_prize": grand,
            "server_day": s.get("server_day"), "total_studies": s.get("total_studies"),
            "monster_studies": s.get("monster_studies"),
            "studies_monster_name": studies_of or None, "studies_monster_id": studies_id,
            "requirements": s.get("requirements") or [], "what_unlocking_does": s.get("what_unlocking_does"),
            "unlocked_message": s.get("unlocked_message"), "rewards": s.get("rewards") or [],
            "free_hunt_id": s.get("free_hunt_id"), "game_monster_id": s.get("monster_id"),
            "sketch": s.get("sketch"),
        })
    if problems:
        sys.exit("\n".join(problems))

    stamp = next_stamp()
    out = Path(args.out) if args.out else MIGRATIONS / f"{stamp}_import_mho_investigation_journey.sql"
    values = ",\n".join(
        f"  ({q(r['id'])}, {n(r['journey'])}, {n(r['step'])}, {n(r['sort_order'])}, {q(r['unlocks_name'])}, "
        f"{q(r['unlocks_monster_id'])}, {'TRUE' if r['is_grand_prize'] else 'FALSE'}, {n(r['server_day'])}, "
        f"{n(r['total_studies'])}, {n(r['monster_studies'])}, {q(r['studies_monster_name'])}, {q(r['studies_monster_id'])}, "
        f"{js(r['requirements'])}, {q(r['what_unlocking_does'])}, {q(r['unlocked_message'])}, {js(r['rewards'])}, "
        f"{q(r['free_hunt_id'])}, {q(r['game_monster_id'])}, {q(r['sketch'])})"
        for r in rows)
    ids = ", ".join(q(r["id"]) for r in rows)

    sql = f"""-- ============================================================
-- Migration: {out.stem.split('_')[0]} — Investigation Journey
-- Source: import/MHO_monster_investigation_journey.json — generated by scripts/import_mho_investigation_journey.py
--   * investigation_journey_steps: the monsters the journey unlocks, in order, and what each needs
--   * requirements / rewards kept as exported (JSON); monsters linked to public.monsters
--   * upserts, and removes steps no longer in the export; safe to re-run
-- ============================================================

BEGIN;

CREATE TABLE IF NOT EXISTS public.investigation_journey_steps (
  id                   TEXT    PRIMARY KEY,          -- export row_id, e.g. '101' = journey 1 step 1
  journey              INTEGER NOT NULL,
  step                 INTEGER NOT NULL,
  sort_order           INTEGER NOT NULL DEFAULT 0,
  unlocks_name         TEXT    NOT NULL,
  unlocks_monster_id   TEXT    REFERENCES public.monsters(id) ON UPDATE CASCADE ON DELETE SET NULL,
  is_grand_prize       BOOLEAN NOT NULL DEFAULT FALSE,
  server_day           INTEGER,                      -- days the game server must have been open
  total_studies        INTEGER,                      -- Investigation Notes studies, any monster
  monster_studies      INTEGER,                      -- studies needed of studies_monster
  studies_monster_name TEXT,
  studies_monster_id   TEXT    REFERENCES public.monsters(id) ON UPDATE CASCADE ON DELETE SET NULL,
  requirements         JSONB   NOT NULL DEFAULT '[]',
  what_unlocking_does  TEXT,
  unlocked_message     TEXT,
  rewards              JSONB   NOT NULL DEFAULT '[]',
  free_hunt_id         TEXT,
  game_monster_id      TEXT,
  sketch               TEXT,
  updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_investigation_journey_steps_order ON public.investigation_journey_steps(journey, step);

ALTER TABLE public.investigation_journey_steps ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "investigation_journey_steps_select_all" ON public.investigation_journey_steps;
CREATE POLICY "investigation_journey_steps_select_all" ON public.investigation_journey_steps FOR SELECT USING (TRUE);
DROP POLICY IF EXISTS "investigation_journey_steps_admin_all" ON public.investigation_journey_steps;
CREATE POLICY "investigation_journey_steps_admin_all" ON public.investigation_journey_steps FOR ALL
  USING (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'))
  WITH CHECK (EXISTS (SELECT 1 FROM public.profiles WHERE id = auth.uid() AND role = 'admin'));

CREATE TEMP TABLE _journey (
  id TEXT, journey INTEGER, step INTEGER, sort_order INTEGER, unlocks_name TEXT, unlocks_monster_id TEXT,
  is_grand_prize BOOLEAN, server_day INTEGER, total_studies INTEGER, monster_studies INTEGER,
  studies_monster_name TEXT, studies_monster_id TEXT, requirements JSONB, what_unlocking_does TEXT,
  unlocked_message TEXT, rewards JSONB, free_hunt_id TEXT, game_monster_id TEXT, sketch TEXT
) ON COMMIT DROP;

INSERT INTO _journey VALUES
{values};

INSERT INTO public.investigation_journey_steps (
  id, journey, step, sort_order, unlocks_name, unlocks_monster_id, is_grand_prize, server_day, total_studies,
  monster_studies, studies_monster_name, studies_monster_id, requirements, what_unlocking_does, unlocked_message,
  rewards, free_hunt_id, game_monster_id, sketch, updated_at
)
SELECT
  j.id, j.journey, j.step, j.sort_order, j.unlocks_name,
  COALESCE((SELECT m.id FROM public.monsters m WHERE m.id = j.unlocks_monster_id),
           (SELECT m.id FROM public.monsters m WHERE m.name = j.unlocks_name AND NOT j.is_grand_prize LIMIT 1)),
  j.is_grand_prize, j.server_day, j.total_studies, j.monster_studies, j.studies_monster_name,
  COALESCE((SELECT m.id FROM public.monsters m WHERE m.id = j.studies_monster_id),
           (SELECT m.id FROM public.monsters m WHERE m.name = j.studies_monster_name LIMIT 1)),
  j.requirements, j.what_unlocking_does, j.unlocked_message, j.rewards, j.free_hunt_id, j.game_monster_id, j.sketch, now()
FROM _journey j
ON CONFLICT (id) DO UPDATE SET
  journey = EXCLUDED.journey, step = EXCLUDED.step, sort_order = EXCLUDED.sort_order,
  unlocks_name = EXCLUDED.unlocks_name, unlocks_monster_id = EXCLUDED.unlocks_monster_id,
  is_grand_prize = EXCLUDED.is_grand_prize, server_day = EXCLUDED.server_day,
  total_studies = EXCLUDED.total_studies, monster_studies = EXCLUDED.monster_studies,
  studies_monster_name = EXCLUDED.studies_monster_name, studies_monster_id = EXCLUDED.studies_monster_id,
  requirements = EXCLUDED.requirements, what_unlocking_does = EXCLUDED.what_unlocking_does,
  unlocked_message = EXCLUDED.unlocked_message, rewards = EXCLUDED.rewards, free_hunt_id = EXCLUDED.free_hunt_id,
  game_monster_id = EXCLUDED.game_monster_id, sketch = EXCLUDED.sketch, updated_at = now();

DELETE FROM public.investigation_journey_steps WHERE id NOT IN ({ids});

COMMIT;
"""
    out.write_text(sql, encoding="utf-8")
    journeys = sorted({r["journey"] for r in rows})
    print(f"{len(rows)} steps in {len(journeys)} journeys -> {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
